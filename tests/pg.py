from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':1200,'height':800});errs=[]
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto('file:///tmp/test_local.html');pg.wait_for_timeout(800)
    pg.evaluate("document.querySelector('[data-act=\"demo\"],[data-act=\"skip\"]')?.click()")
    print(pg.evaluate("[S.track, S.books.find(b=>b.shelf==='reading').t]"))
    id=pg.evaluate("S.books.find(b=>b.shelf==='reading').id")
    pg.evaluate(f"openBook('{id}')");pg.wait_for_timeout(300)
    print('seg',pg.locator('.seg button').count())
    pg.click('.seg button[data-v=pages]');pg.wait_for_timeout(300)
    print('track',pg.evaluate("S.track"))
    pg.fill('input[data-f=pgn]','129');pg.dispatch_event('input[data-f=pgn]','change');pg.wait_for_timeout(300)
    print(pg.evaluate(f"(()=>{{const b=bk('{id}');return [b.pg,b.pages,b.cur,b.pr,progress(b)]}})()"))
    pg.screenshot(path='/tmp/pg1.png')
    pg.evaluate("bd.close()");pg.wait_for_timeout(300)
    print(pg.inner_text('.now .chap'))
    pg.fill('.pgform input','200');pg.click('[data-act=setpg]');pg.wait_for_timeout(300)
    print(pg.inner_text('.now .chap'))
    pg.screenshot(path='/tmp/pg2.png')
    pg.evaluate(f"openBook('{id}')");pg.click('.seg button[data-v=chapters]');pg.wait_for_timeout(300)
    print(pg.inner_text('#bd output') if pg.locator('#bd output').count() else pg.evaluate("bd.innerText.slice(0,400)"))
    print('errs',errs)
    b.close()
